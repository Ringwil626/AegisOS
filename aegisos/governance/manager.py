def create_evolution_proposal(task_id: int, goal: str) -> str:
    """Create evolution proposal from request.
    
    Phase 7 Workflow:
    1. Retrieve historical similar cases
    2. Compute risk forecast
    3. Provide context to AI
    4. AI generates patch with justification
    5. Validate justification exists
    6. Register in database
    
    Args:
        task_id: Task ID that triggered evolution
        goal: Evolution goal description
    
    Returns:
        Proposal path
    """
    ensure_directories()
    
    # Phase 7: Step 1 & 2 - Retrieve historical context and risk forecast
    print(f"[Evolution] Retrieving historical context for: {goal}")
    historical_context, risk_forecast = get_evolution_context(goal)
    
    print(f"[Evolution] Risk assessment: {risk_forecast['risk_level']}")
    print(f"[Evolution] Found {risk_forecast['similar_cases_count']} similar cases")
    print(f"[Evolution] Failure rate: {risk_forecast['failure_rate']*100:.0f}%")
    
    # Phase 7: Critical - If risk is critical, require manual review
    if risk_forecast["risk_level"] == "critical":
        print(f"[Evolution] WARNING: Critical risk detected!")
        print(f"[Evolution] Recommendation: {risk_forecast['recommendation']}")
    
    # Generate unique proposal ID
    proposal_id = generate_proposal_id()
    proposal_path = os.path.join(PROPOSALS_DIR, proposal_id)
    
    # Create proposal directory
    os.makedirs(proposal_path, exist_ok=True)
    
    # Phase 7: Step 3 & 4 - Call AI with historical context
    # In mock mode, we use local generation
    # In production: execute_with_budget_guard(task_id, "kimi", prompt_with_context, ai_call_func)
    patch_bundle = mock_ai_generate_patch_with_context(
        task_id, 
        goal, 
        historical_context,
        risk_forecast
    )
    
    # Phase 7: Step 5 - Validate justification exists
    justification = patch_bundle.get("justification", "")
    if not justification or len(justification) < 20:
        # Reject proposal - missing required justification
        error_msg = "Proposal rejected: Missing justification_against_history"
        print(f"[Evolution] {error_msg}")
        
        # Write error file
        with open(os.path.join(proposal_path, "REJECTED.txt"), "w") as f:
            f.write(error_msg)
        
        # Still create minimal manifest for record
        manifest = create_proposal_manifest(
            proposal_path=proposal_path,
            goal=goal,
            files_changed=[],
            risk_level="rejected",
            justification="REJECTED: " + error_msg,
            historical_context=None
        )
        
        # Register as rejected
        job_id = create_evolution_job(task_id, proposal_path)
        update_evolution_job_status(job_id, "rejected")
        
        return proposal_path
    
    # Write patch file
    patch_path = os.path.join(proposal_path, "patch.diff")
    with open(patch_path, "w") as f:
        f.write(patch_bundle["patch"])
    
    # Write test file
    test_path = os.path.join(proposal_path, "new_tests.py")
    with open(test_path, "w") as f:
        f.write(patch_bundle["tests"])
    
    # Write historical context for review
    context_path = os.path.join(proposal_path, "historical_context.txt")
    with open(context_path, "w") as f:
        f.write(historical_context)
    
    # Create manifest with justification
    manifest = create_proposal_manifest(
        proposal_path=proposal_path,
        goal=goal,
        files_changed=patch_bundle["files_changed"],
        risk_level=patch_bundle["risk_level"],
        justification=justification,
        historical_context={
            "successes": patch_bundle.get("historical_successes_count", 0),
            "failures": patch_bundle.get("historical_failures_count", 0)
        }
    )
    
    # Register in database
    job_id = create_evolution_job(task_id, proposal_path)
    
    # Add to vector index for future retrieval
    context_text = f"{goal} {justification}"
    embedding_id = compute_embedding_id(context_text)
    index = get_vector_index()
    index.add_memory(job_id, goal, justification)
    
    print(f"[Evolution] Created proposal: {proposal_id}")
    print(f"[Evolution] Job ID: {job_id}")
    print(f"[Evolution] Path: {proposal_path}")
    print(f"[Evolution] Justification: {justification[:100]}...")
    
    return proposal_path


def get_proposal_manifest(proposal_path: str) -> dict:
    """Read proposal manifest."""
    manifest_path = os.path.join(proposal_path, "manifest.json")
    if os.path.exists(manifest_path):
        with open(manifest_path, "r") as f:
            return json.load(f)
    return {}


def list_proposals():
    """List all proposals."""
    ensure_directories()
    proposals = []
    for item in os.listdir(PROPOSALS_DIR):
        item_path = os.path.join(PROPOSALS_DIR, item)
        if os.path.isdir(item_path):
            manifest = get_proposal_manifest(item_path)
            proposals.append({
                "id": item,
                "path": item_path,
                "manifest": manifest
            })
    return proposals
