def generate_proposal_id() -> str:
    """Generate unique proposal ID."""
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    return f"evo_{timestamp}"


def create_proposal_manifest(proposal_path: str, goal: str, files_changed: list, 
                             risk_level: str = "medium", justification: str = "",
                             historical_context: dict = None):
    """Create manifest.json for proposal.
    
    Phase 7: AI MUST output justification_against_history.
    If missing, proposal is rejected.
    
    Args:
        proposal_path: Path to proposal directory
        goal: Evolution goal description
        files_changed: List of files to be modified
        risk_level: low/medium/high/critical
        justification: Why this won't repeat past failures
        historical_context: Retrieved historical cases
    """
    manifest = {
        "proposal_id": os.path.basename(proposal_path),
        "goal": goal,
        "target_version": "v1.1",
        "files_changed": files_changed,
        "risk_level": risk_level,
        "requires_migration": False,
        "created_at": time.time(),
        "author": "AI",
        # Phase 7: Required new fields
        "justification_against_history": justification,
        "historical_failures_count": len(historical_context.get("historical_failures", [])) if historical_context else 0,
        "historical_successes_count": len(historical_context.get("historical_successes", [])) if historical_context else 0
    }
    
    manifest_path = os.path.join(proposal_path, "manifest.json")
    with open(manifest_path, "w") as f:
        json.dump(manifest, f, indent=2)
    
    return manifest


